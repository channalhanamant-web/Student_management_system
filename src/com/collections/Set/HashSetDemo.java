package com.collections.Set;

import java.util.HashSet;
import java.util.Set;


public class HashSetDemo {
	public static void main(String[] args) {
		
		Set<String> names = new HashSet<String>();
		names.add("Jatin");
		names.add("Raj");
		names.add("Katrina");
		names.add("Uday");
		
		System.out.println(names);
	}
	
 
}
